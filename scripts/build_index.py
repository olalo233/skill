#!/usr/bin/env python3
"""Generate INDEX.md and index.json from skills/ and vendor/ SKILL.md files.

Suite membership and dependencies for first-party skills live in
.sync/index-source.json; vendor suites are derived from vendor/<suite>/.
Run with --check to verify the committed files are current.
"""
import json
import re
import sys
from pathlib import Path, PurePosixPath

ROOT = Path(__file__).resolve().parents[1]
FM = re.compile(r'\A---\n(.*?)\n---\n', re.S)


def frontmatter(path):
    text = path.read_text(encoding='utf-8')
    match = FM.match(text)
    fields, key = {}, None
    if not match:
        return fields
    for line in match.group(1).splitlines():
        m = re.match(r'([A-Za-z_-]+):\s*(.*)', line)
        if m:
            key = m.group(1)
            fields[key] = m.group(2).strip().strip('"\'')
        elif key and line.startswith((' ', '\t')):
            value = fields[key]
            if value in ('>', '|', '>-', '|-', '>+', '|+'):
                value = ''
            fields[key] = (value + ' ' + line.strip()).strip()
        else:
            key = None
    return fields


def summary_of(description):
    line = description.splitlines()[0].strip()
    sentence = re.split(r'(?<=[.!?])\s+', line)[0]
    return sentence[:160]


def scan(root):
    """Return list of skill entries: name, suite, summary, path, depends."""
    src = json.loads((root / '.sync/index-source.json').read_text())
    suite_of = {s: suite for suite, meta in src['suites'].items() for s in meta['skills']}
    depends = src.get('depends', {})
    entries = []
    for path in sorted((root / 'skills').glob('*/SKILL.md')):
        rel = path.relative_to(root).as_posix()
        name = path.parent.name
        fm = frontmatter(path)
        if name not in suite_of:
            raise SystemExit(f'{rel}: not listed in any suite in .sync/index-source.json')
        entries.append({'name': fm.get('name', name), 'suite': suite_of[name],
                        'summary': summary_of(fm.get('description', '')),
                        'path': rel, 'depends': depends.get(name, [])})
    for path in sorted(root.glob('vendor/**/SKILL.md')):
        rel = path.relative_to(root).as_posix()
        parts = PurePosixPath(rel).parts  # vendor/<suite>/...
        suite = parts[1]
        fm = frontmatter(path)
        entries.append({'name': fm.get('name', path.parent.name), 'suite': suite,
                        'summary': summary_of(fm.get('description', '')),
                        'path': rel, 'depends': depends.get(path.parent.name, [])})
    return entries, src


def render_json(entries):
    return json.dumps({'version': 1, 'generated_by': 'scripts/build_index.py',
                       'skills': entries}, indent=2, ensure_ascii=False) + '\n'


def render_md(entries, src):
    titles = {suite: meta['title'] for suite, meta in src['suites'].items()}
    titles.update({k: v['title'] for k, v in src.get('vendor', {}).items()})
    notes = {k: v['note'] for k, v in src.get('vendor', {}).items()}
    order = list(src['suites']) + sorted({e['suite'] for e in entries} - set(src['suites']))
    lines = ['# Skill index', '',
             'Generated by `scripts/build_index.py`; do not edit by hand.',
             'Each `path` is relative to the repository root. `depends` entries must be',
             'present as sibling directories; they do not need to be read.', '']
    for suite in order:
        group = [e for e in entries if e['suite'] == suite]
        if suite in titles:
            lines.append(f'## {titles.get(suite, suite)}')
        else:
            continue
        lines.append('')
        if suite in notes:
            lines.append(notes[suite])
            lines.append('')
        lines.append('| Skill | Summary | Path | Depends |')
        lines.append('| --- | --- | --- | --- |')
        for e in group:
            deps = ', '.join(e['depends'])
            lines.append(f"| `{e['name']}` | {e['summary']} | `{e['path']}` | {deps} |")
        lines.append('')
    declared = set(src.get('vendor', {})) - {e['suite'] for e in entries}
    for suite in sorted(declared):
        lines.append(f'## {titles[suite]}')
        lines.append('')
        lines.append(notes[suite])
        lines.append('')
        lines.append('_Not vendored yet; see `.sync/upstreams.json` (`vendor_seeded: false`)._')
        lines.append('')
    return '\n'.join(lines)


def build(root):
    entries, src = scan(root)
    return render_md(entries, src), render_json(entries)


if __name__ == '__main__':
    check = '--check' in sys.argv
    md, js = build(ROOT)
    md_path, js_path = ROOT / 'INDEX.md', ROOT / 'index.json'
    if check:
        stale = [str(p.relative_to(ROOT)) for p, want in
                 ((md_path, md), (js_path, js)) if not p.is_file() or p.read_text() != want]
        if stale:
            print('Stale index: ' + ', '.join(stale) + ' — run scripts/build_index.py')
            raise SystemExit(1)
        print('INDEX.md and index.json are up to date.')
    else:
        md_path.write_text(md)
        js_path.write_text(js)
        print(f'Wrote INDEX.md and index.json ({len(json.loads(js)["skills"])} skills).')
